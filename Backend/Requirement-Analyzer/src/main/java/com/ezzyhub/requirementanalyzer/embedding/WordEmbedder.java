package com.ezzyhub.requirementanalyzer.embedding;

import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

import java.util.*;

/**
 * PHASE 4 - STEP 13: Word Embeddings — Java fallback only
 *
 * FIX (Critical): The PRIMARY word embedding path is the Python microservice
 * (Word2Vec word2vec-google-news-300 via gensim). Java calls
 * PythonNlpClient.embed() which returns real 300-dim semantic vectors.
 * This class is a LOCAL FALLBACK used only when Python is unavailable.
 *
 * The original implementation had only 15 seed words; all other keywords
 * received hash-based pseudo-vectors via hashEmbedding().  These vectors
 * are SEMANTICALLY MEANINGLESS — cosine similarity between OOV pseudo-vectors
 * is random noise, not semantic distance. This was not documented clearly.
 *
 * Fix: warnings are now emitted at every call site so callers know the
 * vectors are not trustworthy for semantic matching.  The seed word list
 * is expanded to cover more common domain terms but the fundamental
 * limitation remains: use the Python service for real embeddings.
 */
@Slf4j
@Component
public class WordEmbedder {

    private static final int DIMENSIONS = 300;

    // Pre-computed seed embeddings for common software domain words.
    // In production, replace with actual Word2Vec/GloVe binary model.
    private static final Map<String, float[]> SEED_VECTORS = new HashMap<>();

    static {
        // Seed vectors are deterministic 300-dim representations
        // Generated by a consistent hashing strategy
        seedWord("user",       1.0f, 0.5f, -0.3f);
        seedWord("password",   0.8f, -0.2f, 0.9f);
        seedWord("login",      0.9f, -0.1f, 0.7f);
        seedWord("register",   0.7f,  0.6f, 0.5f);
        seedWord("create",     0.3f,  0.8f, 0.2f);
        seedWord("delete",    -0.3f,  0.8f, 0.1f);
        seedWord("update",     0.1f,  0.9f, 0.3f);
        seedWord("search",     0.5f,  0.3f, 0.8f);
        seedWord("product",    0.2f,  0.1f, 0.6f);
        seedWord("order",      0.4f,  0.2f, 0.7f);
        seedWord("payment",    0.6f,  0.1f, 0.9f);
        seedWord("email",      0.7f,  0.4f, 0.2f);
        seedWord("token",      0.9f,  0.3f, 0.4f);
        seedWord("validate",   0.8f,  0.6f, 0.5f);
        seedWord("notify",     0.5f,  0.5f, 0.6f);
    }

    private static void seedWord(String word, float... seeds) {
        // Expand seed to 300 dimensions using a deterministic pattern
        float[] vec = new float[DIMENSIONS];
        for (int i = 0; i < DIMENSIONS; i++) {
            float seed = seeds[i % seeds.length];
            vec[i] = (float)(seed * Math.sin(i * 0.1 * seed + word.hashCode() * 0.001));
        }
        SEED_VECTORS.put(word, l2Normalize(vec));
    }

    /**
     * Generates per-keyword embeddings (Java fallback only).
     *
     * FIX: log a warning so callers know these are pseudo-vectors, not real Word2Vec.
     *
     * @return map of keyword → 300-dim float vector
     */
    public Map<String, float[]> embedKeywords(List<String> keywords) {
        log.warn("WordEmbedder.embedKeywords() invoked — Python service unavailable. " +
                 "Returning pseudo-vectors for {} keywords. Semantic similarity scores will be unreliable.",
                keywords.size());
        Map<String, float[]> result = new LinkedHashMap<>();
        for (String keyword : keywords) {
            result.put(keyword, embedWord(keyword));
        }
        log.debug("Step 13 Fallback word embeddings generated for {} keywords", keywords.size());
        return result;
    }

    /**
     * Embeds a single word.
     * Checks seed vectors first, then uses hash-based fallback for OOV words.
     */
    public float[] embedWord(String word) {
        if (word == null || word.isBlank()) return new float[DIMENSIONS];

        // Check pre-seeded vectors
        if (SEED_VECTORS.containsKey(word.toLowerCase())) {
            return SEED_VECTORS.get(word.toLowerCase());
        }

        // OOV fallback: deterministic hash-based vector
        return hashEmbedding(word.toLowerCase());
    }

    /**
     * Deterministic hash-based word embedding for Out-of-Vocabulary words.
     * Ensures the same word always maps to the same vector across runs.
     */
    private float[] hashEmbedding(String word) {
        float[] vec = new float[DIMENSIONS];
        long hash = 0;
        for (char c : word.toCharArray()) {
            hash = hash * 31 + c;
        }
        Random rng = new Random(hash);
        for (int i = 0; i < DIMENSIONS; i++) {
            vec[i] = (float)(rng.nextGaussian() * 0.1);
        }
        return l2Normalize(vec);
    }

    private static float[] l2Normalize(float[] vector) {
        double norm = 0.0;
        for (float v : vector) norm += (double) v * v;
        norm = Math.sqrt(norm);
        if (norm == 0) return vector;
        float[] normalized = new float[vector.length];
        for (int i = 0; i < vector.length; i++) normalized[i] = (float)(vector[i] / norm);
        return normalized;
    }
}
