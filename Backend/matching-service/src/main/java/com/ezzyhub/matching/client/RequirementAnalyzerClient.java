package com.ezzyhub.matching.client;

import com.ezzyhub.matching.dto.StoredRequirementDto;
import com.ezzyhub.matching.dto.ReqAnalysisResult;
import org.springframework.http.MediaType;
import java.util.Map;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.core.ParameterizedTypeReference;
import org.springframework.stereotype.Component;
import org.springframework.web.reactive.function.client.WebClient;
import org.springframework.web.reactive.function.client.WebClientResponseException;

import java.util.Collections;
import java.util.List;
import java.util.Optional;

/**
 * HTTP client for the Requirement Analyzer service (Port 8081).
 *
 * Used when no requirements are provided in the match request —
 * the matching service fetches all stored requirements from the
 * Requirement Analyzer database.
 *
 * Endpoint used:
 *   GET /api/v1/requirements          → all stored requirements (summary DTOs)
 *   GET /api/v1/requirements/{reqId}  → single requirement by ID
 *   GET /api/v1/requirements/health   → readiness check
 */
@Slf4j
@Component
public class RequirementAnalyzerClient {

    private final WebClient webClient;

    public RequirementAnalyzerClient(
            @Qualifier("requirementAnalyzerWebClient") WebClient webClient) {
        this.webClient = webClient;
    }

    // ── GET /api/v1/requirements ──────────────────────────────────────────────

    /**
     * Fetch all requirements stored in the Requirement Analyzer DB.
     *
     * The summary DTO includes reqId, originalText, cleanText, keywords (JSON string),
     * actionVerbs (JSON string), and validationStatus. It does NOT include
     * sentenceEmbedding blobs — those are re-generated by the Matching Service
     * via Python /preprocess-and-embed.
     *
     * @return list of stored requirements, or empty list on error
     */
    public List<StoredRequirementDto> fetchAllRequirements() {
        log.info("Fetching all requirements from Requirement Analyzer...");
        try {
            List<StoredRequirementDto> results = webClient.get()
                    .uri("/api/v1/requirements")
                    .retrieve()
                    .bodyToMono(new ParameterizedTypeReference<List<StoredRequirementDto>>() {})
                    .block();

            if (results == null) {
                log.warn("Requirement Analyzer returned null list — treating as empty");
                return Collections.emptyList();
            }
            log.info("Fetched {} requirements from Requirement Analyzer", results.size());
            return results;

        } catch (WebClientResponseException e) {
            log.error("Requirement Analyzer GET /requirements → HTTP {}: {}",
                    e.getStatusCode(), e.getResponseBodyAsString());
            throw new RuntimeException(
                    "Failed to fetch requirements from Requirement Analyzer (HTTP "
                            + e.getStatusCode() + "): " + e.getResponseBodyAsString(), e);
        } catch (Exception e) {
            log.error("Cannot reach Requirement Analyzer: {}", e.getMessage());
            throw new RuntimeException(
                    "Cannot connect to Requirement Analyzer at port 8081. "
                            + "Please start it before using auto-fetch mode. Error: " + e.getMessage(), e);
        }
    }

    // ── GET /api/v1/requirements/{reqId} ──────────────────────────────────────

    /**
     * Fetch a single requirement by its ID.
     *
     * @param reqId the requirement identifier (e.g. "FR-2.1.1")
     * @return the stored requirement if found
     */
    public Optional<StoredRequirementDto> fetchByReqId(String reqId) {
        try {
            StoredRequirementDto dto = webClient.get()
                    .uri("/api/v1/requirements/{reqId}", reqId)
                    .retrieve()
                    .bodyToMono(StoredRequirementDto.class)
                    .block();
            return Optional.ofNullable(dto);
        } catch (WebClientResponseException.NotFound e) {
            return Optional.empty();
        } catch (Exception e) {
            log.warn("Failed to fetch requirement {}: {}", reqId, e.getMessage());
            return Optional.empty();
        }
    }

    // ── Health check ──────────────────────────────────────────────────────────

    /**
     * Check if the Requirement Analyzer service is reachable.
     *
     * @return true if service returns UP status
     */
    public boolean isHealthy() {
        try {
            var response = webClient.get()
                    .uri("/api/v1/requirements/health")
                    .retrieve()
                    .bodyToMono(java.util.Map.class)
                    .block();
            if (response == null) return false;
            return "UP".equals(response.get("status"));
        } catch (Exception e) {
            log.warn("Requirement Analyzer health check failed: {}", e.getMessage());
            return false;
        }
    }

    // ── Process raw requirement TEXT through the analyzer (clean + embed) ──────

    /**
     * Sends raw requirement strings to Requirement-Analyzer's batch analyze endpoint,
     * which cleans/structures each one and embeds it (via the shared Python /embed,
     * so embeddings are compatible with code chunks). Returns one result per input,
     * or an empty list on any failure (caller then falls back to Python directly).
     *
     * POST /api/v1/requirements/analyze/batch  body: {"requirements":[...],"skipAiValidation":true}
     */
    public List<ReqAnalysisResult> analyzeBatch(List<String> requirementTexts) {
        try {
            Map<String, Object> body = Map.of(
                    "requirements", requirementTexts,
                    "skipAiValidation", true);
            List<ReqAnalysisResult> results = webClient.post()
                    .uri("/api/v1/requirements/analyze/batch")
                    .contentType(MediaType.APPLICATION_JSON)
                    .bodyValue(body)
                    .retrieve()
                    .bodyToMono(new ParameterizedTypeReference<List<ReqAnalysisResult>>() {})
                    .block();
            if (results == null) return Collections.emptyList();
            log.info("Requirement-Analyzer analyze/batch ✓ {} of {} processed",
                    results.size(), requirementTexts.size());
            return results;
        } catch (Exception e) {
            log.warn("Requirement-Analyzer analyze/batch failed ({}) — will embed via Python instead",
                    e.getMessage());
            return Collections.emptyList();
        }
    }
}